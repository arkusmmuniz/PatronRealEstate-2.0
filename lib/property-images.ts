// Generate multiple images for property details page
export const generatePropertyGallery = (listingID: string, propertyType: string, city: string, state: string): string[] => {
  // Create a more complex hash using multiple factors
  const combinedString = `${listingID}-${propertyType}-${city}-${state}`;
  const hash = combinedString.split('').reduce((a, b) => {
    a = ((a << 5) - a) + b.charCodeAt(0);
    return a & a;
  }, 0);
  
  // Generate 5 unique indices
  const indices: number[] = [];
  const poolLength = realistictPropertyImages.length;
  
  for (let i = 0; i < 5; i++) {
    const seed = (hash + i * 17) % poolLength;
    let index = Math.abs(seed) % poolLength;
    
    // Avoid duplicates
    if (!indices.includes(index)) {
      indices.push(index);
    } else {
      let nextIndex = (index + 1) % poolLength;
      while (indices.includes(nextIndex) && nextIndex !== index) {
        nextIndex = (nextIndex + 1) % poolLength;
      }
      indices.push(nextIndex);
    }
  }
  
  return indices.map(index => realistictPropertyImages[index]);
};

